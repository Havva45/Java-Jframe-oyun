    private void dosyaVeArayuzKontrolu() {
        File dosya = new File(dosyayolu);
        
        if (dosya.exists()) {
            sifreMevcutMu = true;
            jLabel1.setText("Lütfen şifrenizi girin:");
 

            try {
                Scanner dosyaOkuyucu = new Scanner(dosya);
                
                if (dosyaOkuyucu.hasNextLine()) {
                    dosyadakiSifre = dosyaOkuyucu.nextLine();
                }
                
                dosyaOkuyucu.close(); 
                
            } catch (Exception e) {}
        } else {
            sifreMevcutMu = false;
            jLabel1.setText("Bir şifre belirleyin:");
            
        }
    }
  private void gecenSureSayaciniBaslat() {
        Timer zamanlayici = new Timer(1000, e -> {
            gecenSaniye++;
            jLabelSaat.setText("Geçen Süre: " + gecenSaniye + " saniye");
        }); 
        zamanlayici.start();
    }
  
    private void logKaydet(String durumMesaji) {
        try (FileWriter logYazici = new FileWriter(logdosya, true)) { 
            java.util.Date gercekZaman = new java.util.Date();

            logYazici.write("[" + gercekZaman.toString() + "] - " + durumMesaji + "\n");
        } 
        catch (Exception e) {}
}
    
    
