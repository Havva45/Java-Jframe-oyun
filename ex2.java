    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String girilenSifre = new String(jPasswordField1.getPassword());
        
        // Boş bırakma kontrolü
        if (girilenSifre.equals("")) {
            JOptionPane.showMessageDialog(this, "Şifre alanını boş bırakmayınız:");
            return;
        }
        
        if (!sifreMevcutMu) {
           
            try {
                FileWriter yazici = new FileWriter(dosyayolu);
                yazici.write(girilenSifre);
                yazici.close(); 
                logKaydet("Kullanıcı şifre oluşturdu, sisteme kaydedildi.");
                
                JOptionPane.showMessageDialog(this, "Oyun açılıyor...");
                oyunuBaslat();
            } 
            catch (Exception e) {}
        } 
        else {
            
            if (girilenSifre.equals(dosyadakiSifre)) {
                logKaydet("BAŞARILI GİRİŞ:");
                JOptionPane.showMessageDialog(this, "Şifre Doğru!");
                gecenSureSayaciniBaslat();
                oyunuBaslat();
            } 
            else {

                hataliGirisSayisi++;
                
                if (hataliGirisSayisi >= 3) {
                    logKaydet("Üst üste 3 defa hatalı şifre girildi!");
                   
                    JOptionPane.showMessageDialog(this, "Program sonlandırılıyor.", "Sistem Kilitlendi", JOptionPane.ERROR_MESSAGE);
                    System.exit(0); 
                } else {
                    int kalanHak = 3 - hataliGirisSayisi;
                    logKaydet("Hatalı Giriş Denemesi: Kullanıcı '" + girilenSifre + "' şifresini denedi. Kalan hak: " + kalanHak);
                    JOptionPane.showMessageDialog(this, "Hatalı Şifre! Kalan hakkınız: " + kalanHak, "Hata", JOptionPane.WARNING_MESSAGE);
                    jPasswordField1.setText("");
                }
            }
        }
    }//GEN-LAST:event_jButton1ActionPerformed
